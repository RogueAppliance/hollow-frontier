package com.hollowfrontier.registry;

import com.hollowfrontier.HollowFrontier;

import net.minecraft.core.HolderGetter;
import net.minecraft.core.registries.Registries;
import net.minecraft.data.worldgen.BootstrapContext;
import net.minecraft.resources.ResourceKey;
import net.minecraft.tags.TagKey;
import net.minecraft.world.entity.EquipmentSlotGroup;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.enchantment.Enchantment;
import net.minecraft.world.item.enchantment.EnchantmentHelper;
import net.minecraft.world.level.Level;

/**
 * The gun enchantments (22), a datapack registry: keys here, entries generated by datagen (bootstrap below). They carry no
 * effect components: the guns read their levels (GunEnchantments) because the shots are hitscan, not projectiles, and
 * vanilla's damage and spread effects only reach arrows and tridents.
 */
public final class ModEnchantments {
    private ModEnchantments() {}

    public static final ResourceKey<Enchantment> RIFLING = key("rifling");
    public static final ResourceKey<Enchantment> QUICK_LOAD = key("quick_load");
    public static final ResourceKey<Enchantment> DEADEYE = key("deadeye");
    public static final ResourceKey<Enchantment> CHOKE = key("choke");
    public static final ResourceKey<Enchantment> DRY_POWDER = key("dry_powder");
    public static final ResourceKey<Enchantment> FRUGAL = key("frugal");

    public static void bootstrap(BootstrapContext<Enchantment> context) {
        HolderGetter<Item> items = context.lookup(Registries.ITEM);
        // Costs follow the vanilla enchantment each one is most like: Power, Quick Charge, Impaling, Piercing, Aqua Affinity, Looting.
        register(context, RIFLING, items, ModTags.Items.ENCHANTABLE_MUZZLELOADER, 10, 4,
                Enchantment.dynamicCost(1, 10), Enchantment.dynamicCost(16, 10), 1);
        register(context, QUICK_LOAD, items, ModTags.Items.ENCHANTABLE_MUZZLELOADER, 5, 3,
                Enchantment.dynamicCost(12, 20), Enchantment.constantCost(50), 2);
        register(context, DEADEYE, items, ModTags.Items.ENCHANTABLE_GUN, 2, 3,
                Enchantment.dynamicCost(1, 8), Enchantment.dynamicCost(21, 8), 4);
        register(context, CHOKE, items, ModTags.Items.ENCHANTABLE_SHOTGUN, 5, 3,
                Enchantment.dynamicCost(1, 10), Enchantment.constantCost(50), 2);
        register(context, DRY_POWDER, items, ModTags.Items.ENCHANTABLE_MUZZLELOADER, 2, 1,
                Enchantment.constantCost(1), Enchantment.constantCost(41), 4);
        // Frugal and Infinity don't go together: Infinity already spends nothing
        context.register(FRUGAL, builder(items, ModTags.Items.ENCHANTABLE_MUZZLELOADER, 2, 3,
                Enchantment.dynamicCost(15, 9), Enchantment.dynamicCost(65, 9), 4)
                .exclusiveWith(context.lookup(Registries.ENCHANTMENT).getOrThrow(ModTags.Enchantments.EXCLUSIVE_SET_AMMO))
                .build(FRUGAL.identifier()));
    }

    private static void register(BootstrapContext<Enchantment> context, ResourceKey<Enchantment> key, HolderGetter<Item> items,
            TagKey<Item> supported, int weight, int maxLevel, Enchantment.Cost minCost, Enchantment.Cost maxCost, int anvilCost) {
        context.register(key, builder(items, supported, weight, maxLevel, minCost, maxCost, anvilCost).build(key.identifier()));
    }

    private static Enchantment.Builder builder(HolderGetter<Item> items, TagKey<Item> supported, int weight, int maxLevel,
            Enchantment.Cost minCost, Enchantment.Cost maxCost, int anvilCost) {
        return Enchantment.enchantment(Enchantment.definition(items.getOrThrow(supported), weight, maxLevel, minCost, maxCost,
                anvilCost, EquipmentSlotGroup.HAND));
    }

    /** The level of {@code key} on {@code stack}; 0 if it hasn't got it (or the enchantment isn't loaded). */
    public static int level(Level level, ResourceKey<Enchantment> key, ItemStack stack) {
        if (stack.isEmpty()) {
            return 0;
        }
        return level.registryAccess().lookupOrThrow(Registries.ENCHANTMENT).get(key)
                .map(holder -> EnchantmentHelper.getItemEnchantmentLevel(holder, stack)).orElse(0);
    }

    private static ResourceKey<Enchantment> key(String name) {
        return ResourceKey.create(Registries.ENCHANTMENT, HollowFrontier.id(name));
    }
}
